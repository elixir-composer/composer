defmodule Mix.Tasks.Composer.InitTest do
  # --from reads the :composer application env.
  use ExUnit.Case, async: false

  import Igniter.Test
  import Composer.Test.Cookbooks

  alias Composer.{Discovery, Recipe, Resolver}

  @recipe "lib/composer/test/recipes/app.exs"

  defp content(igniter, path) do
    igniter.rewrite |> Rewrite.source!(path) |> Rewrite.Source.get(:content)
  end

  defp generated(argv \\ []) do
    igniter = Igniter.compose_task(test_project(), Mix.Tasks.Composer.Init, argv)
    assert_creates(igniter, @recipe)
    {igniter, content(igniter, @recipe)}
  end

  test "writes the cookbook layout" do
    {igniter, content} = generated()
    assert content =~ "generated by `mix composer.init`"

    cookbook = content(igniter, "lib/composer/test.ex")
    assert cookbook =~ "defmodule Composer.Test do"
    assert cookbook =~ "use Composer.Cookbook"

    # Composer is a dev-only dependency, so the cookbook is guarded.
    assert cookbook =~ "if Code.ensure_loaded?(Composer) do"
    assert_creates(igniter, "lib/composer/test/steps/.gitkeep")
    assert_creates(igniter, "lib/composer/test/manifest.exs")
    assert Enum.any?(igniter.notices, &(&1 =~ "mix composer.recipe.run /app/default"))

    # The manifest lists the recipe with its shortdoc, so lint passes.
    {manifest, _} = Code.eval_string(content(igniter, "lib/composer/test/manifest.exs"))

    assert manifest.recipes == [
             %{id: "app/default", shortdoc: "A starter set of steps, in a sensible order"}
           ]
  end

  test "the default recipe is a valid, formatted chapter with every flag declared" do
    {_igniter, content} = generated()

    {chapter, _binding} = Code.eval_string(content)
    assert {[default], []} = Recipe.Chapter.check(chapter, @recipe, "test")
    assert default.shortdoc == "A starter set of steps, in a sensible order"
    assert default.doc =~ "A starter set of steps"
    assert default.flags == []
    assert content == content |> Code.format_string!() |> IO.iodata_to_binary() |> Kernel.<>("\n")
    assert content =~ "This project's chapter"
  end

  test "every step carries its description from the step's summary" do
    {_igniter, content} = generated()

    assert content =~
             ~r/# Installs oban and runs the package's own igniter installer\n\s+"hex:oban",/
  end

  test "the default recipe references only resolvable steps, without warnings" do
    {:ok, cookbooks} = Discovery.cookbooks(apps: [])

    for ref <- Mix.Tasks.Composer.Init.cookbook() do
      assert {:ok, _} = Resolver.find_step(cookbooks, ref, nil), "unknown step #{ref}"
    end
  end

  describe "--from" do
    @tag :tmp_dir
    test "copies a recipe instead of the cookbook, qualifying same-chapter uses", %{
      tmp_dir: dir
    } do
      File.mkdir_p!(Path.join(dir, "recipes"))

      File.write!(Path.join(dir, "recipes/mine.exs"), """
      [
        base: [shortdoc: "Base", steps: ["cb_std:completions:mix"]],
        app: [
          shortdoc: "Mine",
          doc: "My app.",
          flags: [gigalixir: "Deploy"],
          steps: ["./base", {"./base", if: :gigalixir}, {"cb_std:completions:composer", if: :gigalixir}]
        ]
      ]
      """)

      Application.put_env(:composer, :discovery, cookbooks: [code_cookbook(dir)])
      on_exit(fn -> Application.delete_env(:composer, :discovery) end)

      {igniter, content} = generated(["--from", "mine/mine/app"])

      assert content =~ "Copied from mine/mine/app"
      assert content =~ "by `mix composer.init --from mine/mine/app`"
      refute content =~ "hex:oban"

      {chapter, _} = Code.eval_string(content)

      assert chapter == [
               default: [
                 shortdoc: "Mine",
                 doc: "My app.",
                 flags: [gigalixir: "Deploy"],
                 steps: [
                   "mine/mine/base",
                   {"mine/mine/base", if: :gigalixir},
                   {"cb_std:completions:composer", if: :gigalixir}
                 ]
               ]
             ]

      {manifest, _} = Code.eval_string(content(igniter, "lib/composer/test/manifest.exs"))
      assert manifest.recipes == [%{id: "app/default", shortdoc: "Mine"}]
    end

    test "raises for an unknown recipe" do
      assert_raise Mix.Error, ~r/No recipe or step is named "nope"/, fn ->
        Igniter.compose_task(test_project(), Mix.Tasks.Composer.Init, ["--from", "nope"])
      end
    end
  end
end
