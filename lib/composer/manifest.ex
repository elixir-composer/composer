defmodule Composer.Manifest do
  @moduledoc """
  A cookbook's static manifest: `lib/composer/<package>/manifest.exs`.

  The manifest is plain data - the cookbook's name, package and version,
  and every step's id, summary and facets, and every recipe's id
  (`"group/name"`) and shortdoc - so tools such as shell completion can read a cookbook without
  running its code.

  It is written by `mix composer.cookbook.manifest` and committed. It is
  never written at compile time, and `mix composer.cookbook.lint` fails when
  it is out of date.
  """

  alias Composer.Cookbook

  @header """
  # Generated by `mix composer.cookbook.manifest`. Do not edit by hand.
  # `mix composer.cookbook.lint` fails when this file is out of date.
  """

  @doc "Builds a cookbook's manifest data, sorted by id."
  @spec build(Cookbook.t()) :: map()
  def build(%Cookbook{} = cookbook) do
    %{
      name: cookbook.name,
      package: cookbook.app,
      version: version(cookbook.app),
      steps: cookbook |> Cookbook.steps() |> Enum.map(&step/1),
      recipes: recipes(cookbook)
    }
  end

  @doc """
  Returns `%{id: "group/name", shortdoc: "..."}` for every recipe of a
  cookbook, sorted by id. A recipe whose group fails to load gets an empty
  shortdoc; lint reports the group.
  """
  @spec recipes(Cookbook.t()) :: [%{id: String.t(), shortdoc: String.t()}]
  def recipes(%Cookbook{} = cookbook) do
    {loaded, _errors} = Cookbook.load_recipes(cookbook)
    shortdocs = Map.new(loaded, &{&1.id, &1.shortdoc})

    for id <- Cookbook.recipes(cookbook), do: %{id: id, shortdoc: Map.get(shortdocs, id, "")}
  end

  @doc "Renders manifest data as formatted Elixir source, deterministically."
  @spec render(map()) :: String.t()
  def render(data) do
    # Atom-keyed maps print in atom-table order, which differs between VMs,
    # so keys are sorted explicitly.
    body =
      data
      |> inspect(
        pretty: true,
        limit: :infinity,
        printable_limit: :infinity,
        custom_options: [sort_maps: true]
      )
      |> Code.format_string!()
      |> IO.iodata_to_binary()

    @header <> "\n" <> body <> "\n"
  end

  @doc "The manifest's path inside the cookbook's source tree."
  @spec path(Cookbook.t()) :: Path.t() | nil
  def path(%Cookbook{} = cookbook) do
    case Cookbook.source_dir(cookbook) do
      nil -> nil
      dir -> Path.join(dir, "manifest.exs")
    end
  end

  @doc """
  Reads a committed manifest. It is plain data, so evaluating it runs no
  cookbook code.
  """
  @spec read(Cookbook.t()) :: {:ok, map()} | :error
  def read(%Cookbook{} = cookbook) do
    with path when is_binary(path) <- path(cookbook),
         true <- File.regular?(path),
         {%{steps: steps, recipes: recipes} = data, _} when is_list(steps) and is_list(recipes) <-
           Code.eval_file(path) do
      {:ok, data}
    else
      _ -> :error
    end
  rescue
    _ -> :error
  end

  defp step(meta) do
    %{
      id: meta.id,
      summary: meta.summary,
      action: meta.action,
      frameworks: meta.frameworks,
      capability: meta.capability,
      phase: meta.phase,
      stability: meta.stability,
      tags: meta.tags,
      requires: meta.requires,
      provides: meta.provides,
      conflicts: meta.conflicts
    }
  end

  defp version(nil), do: nil

  defp version(app) do
    Application.load(app)

    case Application.spec(app, :vsn) do
      nil -> nil
      vsn -> to_string(vsn)
    end
  end
end
